// Fonction pour générer toutes les combinaisons de mots-clés
export function generateAllKeywords(): string[] {
  const allKeywords: string[] = [];
  
  // Ajouter tous les mots-clés primaires
  Object.values(PRIMARY_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter tous les mots-clés long-tail
  Object.values(LONG_TAIL_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter tous les mots-clés régionaux
  Object.values(REGIONAL_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter tous les mots-clés par secteur
  Object.values(SECTOR_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter tous les mots-clés par fonctionnalité
  Object.values(FEATURE_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter tous les mots-clés par page
  Object.values(PAGE_KEYWORDS).forEach(category => {
    allKeywords.push(...category);
  });
  
  // Ajouter les mots-clés FAQ
  allKeywords.push(...FAQ_KEYWORDS);
  
  // Supprimer les doublons et retourner
  return [...new Set(allKeywords)];
}

